// Writes typed ABI modules for fe/be from Foundry artifacts. No dependencies.
// Usage: forge build && node scripts/export-abi.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const contracts = [
  ["MockUSDC", "mockUsdcAbi"],
  ["ShipmentManager", "shipmentManagerAbi"],
  ["TibaPool", "tibaPoolAbi"],
]

const outDir = join(root, "abi")
mkdirSync(outDir, { recursive: true })

for (const [name, exportName] of contracts) {
  const artifactPath = join(root, "out", `${name}.sol`, `${name}.json`)
  let artifact
  try {
    artifact = JSON.parse(readFileSync(artifactPath, "utf8"))
  } catch {
    console.error(`Missing artifact ${artifactPath}. Run "forge build" first.`)
    process.exit(1)
  }
  const body =
    `// Generated by scripts/export-abi.mjs from out/${name}.sol/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
  const file = join(outDir, `${exportName}.ts`)
  writeFileSync(file, body)
  console.log(`wrote abi/${exportName}.ts (${artifact.abi.length} entries)`)
}
