import { readFileSync, writeFileSync } from "node:fs"
const files = [
  "0001_init.sql",
  "0002_gas_topups.sql",
  "0003_api_integrity.sql",
  "0004_location_source.sql",
  "0005_trip_pickup_broadcast.sql",
  "0006_quantity_pool_events.sql",
]
const body = files
  .map((file) => {
    const sql = readFileSync(new URL(`../supabase/migrations/${file}`, import.meta.url), "utf8")
    return `-- ${file}\n${sql.replace(/^begin;\s*$/gim, "").replace(/^commit;\s*$/gim, "")}`
  })
  .join("\n\n")
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  `-- Generated by node be/scripts/bundle-migrations.mjs.\n-- Run ONCE in Supabase SQL Editor for a new project.\n-- For an existing database, run only unapplied migrations in numeric order.\n-- All changes commit together; any error rolls back the entire setup.\nbegin;\n\n${body}\n\ncommit;\n`,
)
